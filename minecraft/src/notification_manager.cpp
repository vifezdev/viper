void NotificationManager::add(const std::string& title,
                               const std::string& message,
                               NotificationType type,
                               u32 durationMs)
{
    std::lock_guard<std::mutex> lock(m_mutex);

    Notification notif;
    notif.id = m_nextId++;
    notif.title = title;
    notif.message = message;
    notif.type = type;
    notif.durationMs = durationMs;
    notif.startTime = std::chrono::steady_clock::now();

    m_notifications.push_back(notif);

    VIPER_LOG_MC("[NOTIFY] [{}] {}: {}",
                 type == NotificationType::Success ? "SUCCESS" :
                 type == NotificationType::Warning ? "WARN" :
                 type == NotificationType::Error   ? "ERROR" : "INFO",
                 title, message);
}

void NotificationManager::notifySuccess(const std::string& message, const std::string& title) {
    add(title, message, NotificationType::Success, 4500);
}

void NotificationManager::notifyInfo(const std::string& message, const std::string& title) {
    add(title, message, NotificationType::Info, 4000);
}

void NotificationManager::notifyWarning(const std::string& message, const std::string& title) {
    add(title, message, NotificationType::Warning, 5000);
}

void NotificationManager::notifyError(const std::string& message, const std::string& title) {
    add(title, message, NotificationType::Error, 6000);
}

void NotificationManager::update() {
    std::lock_guard<std::mutex> lock(m_mutex);
    auto now = std::chrono::steady_clock::now();

    m_notifications.erase(
        std::remove_if(m_notifications.begin(), m_notifications.end(),
            [now](const Notification& n) {
                auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds>(
                    now - n.startTime).count();
                return elapsed >= n.durationMs;
            }),
        m_notifications.end());
}

void NotificationManager::clear() {
    std::lock_guard<std::mutex> lock(m_mutex);
    m_notifications.clear();
}

bool NotificationManager::hasActiveNotifications() const {
    std::lock_guard<std::mutex> lock(m_mutex);
    return !m_notifications.empty();
}





void NotificationManager::render(int screenWidth, int screenHeight) {
    std::lock_guard<std::mutex> lock(m_mutex);

    
    auto now = std::chrono::steady_clock::now();
    m_notifications.erase(
        std::remove_if(m_notifications.begin(), m_notifications.end(),
            [now](const Notification& n) {
                auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds>(
                    now - n.startTime).count();
                return elapsed >= n.durationMs;
            }),
        m_notifications.end());

    if (m_notifications.empty()) return;

    if (screenWidth <= 0 || screenHeight <= 0) {
        screenWidth = 854;
        screenHeight = 480;
    }

    
    glPushAttrib(GL_ALL_ATTRIB_BITS);
    glMatrixMode(GL_PROJECTION);
    glPushMatrix();
    glLoadIdentity();
    glOrtho(0, screenWidth, screenHeight, 0, -1, 1);
    glMatrixMode(GL_MODELVIEW);
    glPushMatrix();
    glLoadIdentity();

    glDisable(GL_DEPTH_TEST);
    glDisable(GL_LIGHTING);
    glDisable(GL_CULL_FACE);
    glDisable(GL_TEXTURE_2D);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    const float cardWidth = 240.0f;
    const float cardHeight = 42.0f;
    const float marginRight = 16.0f;
    const float marginTop = 16.0f;
    const float cardSpacing = 8.0f;
    const float borderStripWidth = 4.0f;

    float currentY = marginTop;

    for (const auto& notif : m_notifications) {
        float alpha = notif.getAlpha();
        if (alpha <= 0.001f) continue;

        float slide = notif.getSlideOffset();
        float cardX = screenWidth - cardWidth - marginRight + slide;
        float cardY = currentY;

        u8 bgA = static_cast<u8>(215.0f * alpha);
        u8 borderA = static_cast<u8>(240.0f * alpha);
        u8 textA = static_cast<u8>(255.0f * alpha);

        
        u8 stripeR = 88, stripeG = 166, stripeB = 255;  
        switch (notif.type) {
            case NotificationType::Success:
                stripeR = 63;  stripeG = 185; stripeB = 80;   
                break;
            case NotificationType::Warning:
                stripeR = 210; stripeG = 153; stripeB = 34;   
                break;
            case NotificationType::Error:
                stripeR = 248; stripeG = 81;  stripeB = 73;   
                break;
            case NotificationType::Info:
            default:
                stripeR = 88;  stripeG = 166; stripeB = 255;  
                break;
        }

        
        drawRect(cardX, cardY, cardWidth, cardHeight, 15, 20, 28, bgA);

        
        drawOutlineRect(cardX, cardY, cardWidth, cardHeight, 1.0f, 48, 54, 65, static_cast<u8>(180.0f * alpha));

        
        drawRect(cardX, cardY, borderStripWidth, cardHeight, stripeR, stripeG, stripeB, borderA);

        
        float progress = notif.getProgress();
        float barWidth = (cardWidth - borderStripWidth) * (1.0f - progress);
        if (barWidth > 0.0f) {
            drawRect(cardX + borderStripWidth, cardY + cardHeight - 2.0f,
                     barWidth, 2.0f, stripeR, stripeG, stripeB, static_cast<u8>(200.0f * alpha));
        }

        
        float textX = cardX + borderStripWidth + 10.0f;
        float titleY = cardY + 8.0f;
        float msgY = cardY + 22.0f;

        drawText(textX, titleY, notif.title, 230, 237, 243, textA);
        drawText(textX, msgY, notif.message, 140, 148, 158, textA);

        currentY += cardHeight + cardSpacing;
    }

    
    glPopMatrix();
    glMatrixMode(GL_PROJECTION);
    glPopMatrix();
    glPopAttrib();
}





