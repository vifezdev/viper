float Notification::getProgress() const {
    auto now = std::chrono::steady_clock::now();
    auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds>(now - startTime).count();
    if (elapsed <= 0) return 0.0f;
    if (elapsed >= durationMs) return 1.0f;
    return static_cast<float>(elapsed) / static_cast<float>(durationMs);
}

float Notification::getAlpha() const {
    auto now = std::chrono::steady_clock::now();
    auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds>(now - startTime).count();

    const float fadeInMs = 200.0f;
    const float fadeOutMs = 300.0f;
    const float totalMs = static_cast<float>(durationMs);

    if (elapsed < 0) return 0.0f;
    if (elapsed < fadeInMs) {
        return static_cast<float>(elapsed) / fadeInMs;
    }
    if (elapsed > (totalMs - fadeOutMs)) {
        float remaining = totalMs - static_cast<float>(elapsed);
        return std::max(0.0f, remaining / fadeOutMs);
    }
    return 1.0f;
}

float Notification::getSlideOffset() const {
    auto now = std::chrono::steady_clock::now();
    auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds>(now - startTime).count();

    const float slideInMs = 250.0f;
    if (elapsed < slideInMs) {
        float t = static_cast<float>(elapsed) / slideInMs;
        float ease = 1.0f - std::pow(1.0f - t, 3.0f);
        return (1.0f - ease) * 260.0f;
    }
    return 0.0f;
}





